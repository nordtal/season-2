/**
 * Holds {@link Glyphs}, the three font files and the pack's PNGs to each other.
 *
 * <h2>Why a test and not a look</h2>
 * The three are mirrors of one allocation - {@code resource-pack/README.md}'s code point table says
 * so - and every way they can drift is invisible until a client renders it. A constant the font
 * does not declare draws a missing-glyph box; a font entry pointing at a texture that is not there
 * draws nothing; a cell the sheet never filled in draws a blank the same width as the glyph. None
 * of those fail a build, none of them log anything, and the one that actually happened - a boss bar
 * drawing the admin nametag, because the component named no font - sat in a screenshot for four
 * days before anybody read it as a bug rather than as missing art.
 *
 * <p>This is the check that would have caught the next one cheaply. It runs on {@code check}, needs
 * no server and no Docker, and every file it reads is declared in {@code common/build.gradle.kts}
 * so that editing the pack actually re-runs it.</p>
 *
 * <h2>What it cannot say</h2>
 * That the art is any good. Almost all of it is placeholder-quality, generated by
 * {@code resource-pack/tools/generate_dummy_textures.py}; "has pixels in the right cell" is the
 * whole claim. Which placeholders deserve real art is a decision for the owner, and it is on the
 * checklist outside this repository.
 */
class ResourcePackTest {

    private static final String ASSETS = "resource-pack/src/assets";

    private static final FontFile DEFAULT_FONT =
            FontFile.load("minecraft:default", ASSETS + "/minecraft/font/default.json");
    private static final FontFile BOARD_FONT =
            FontFile.load(Glyphs.FONT_BOARD, ASSETS + "/nordtal/font/board.json");
    private static final FontFile BOSSBAR_FONT =
            FontFile.load(Glyphs.FONT_BOSSBAR, ASSETS + "/nordtal/font/bossbar.json");

    private static final List<FontFile> FONTS = List.of(DEFAULT_FONT, BOARD_FONT, BOSSBAR_FONT);

    /**
     * The message keys whose text is drawn inside a boss bar, mirroring what
     * {@code SmpHud} and {@code HudRenderer} actually pass to {@code Messages}.
     *
     * <p>{@code smp.milestone.} is broader than the HUD needs - {@code smp.milestone.completed} is
     * a chat line - but a milestone's display name is looked up under the same prefix and there is
     * no way to tell the two apart from here. Checking one chat string too many is the safe
     * direction: everything the boss bar font can draw, chat can draw too.</p>
     */
    private static final List<String> HUD_KEY_PREFIXES =
            List.of("smp.hud.", "smp.world.", "smp.milestone.", "smp.navigate.", "hg.hud.");

    private static final List<String> HUD_BUNDLES = List.of(
            "smp/src/main/resources/messages/smp/en.properties",
            "smp/src/main/resources/messages/smp/de.properties",
            "hunger-games/src/main/resources/messages/hunger-games/en.properties",
            "hunger-games/src/main/resources/messages/hunger-games/de.properties");

    @Test
    @DisplayName("every Glyphs constant is declared by the font its name says it belongs to")
    void everyConstantIsInItsFont() {
        final List<String> missing = new ArrayList<>();
        forEachGlyph((name, value) -> {
            final FontFile font = fontFor(name);
            if (value.codePointCount(0, value.length()) != 1) {
                return;
            }
            if (!font.covers(value.codePointAt(0))) {
                missing.add("Glyphs.%s = U+%04X is not declared in %s"
                        .formatted(name, value.codePointAt(0), font.id()));
            }
        });
        assertEquals(List.of(), missing,
                "Glyphs, the font files and resource-pack/README.md's allocation table are three"
                        + " mirrors of one table - a constant missing from its font draws a"
                        + " missing-glyph box, and nothing else says so");
    }

    @Test
    @DisplayName("every bitmap provider names a texture that exists")
    void everyProviderHasItsTexture() {
        final List<String> missing = new ArrayList<>();
        for (final FontFile font : FONTS) {
            for (final FontFile.Bitmap bitmap : font.bitmaps()) {
                if (!Files.isRegularFile(bitmap.texture())) {
                    missing.add(font.id() + " -> " + bitmap.textureId());
                }
            }
        }
        assertEquals(List.of(), missing, "a font entry pointing at a texture that is not in the"
                + " pack draws nothing at all, and the client logs nothing about it");
    }

    @Test
    @DisplayName("every character a font declares has pixels in its cell")
    void everyDeclaredCharacterIsDrawn() {
        final List<String> blank = new ArrayList<>();
        for (final FontFile font : FONTS) {
            for (final FontFile.Bitmap bitmap : font.bitmaps()) {
                final BufferedImage image = read(bitmap.texture());
                final int cellWidth = image.getWidth() / bitmap.columns();
                final int cellHeight = image.getHeight() / bitmap.rows();
                for (int row = 0; row < bitmap.rows(); row++) {
                    for (int column = 0; column < bitmap.columns(); column++) {
                        final int codePoint = bitmap.grid().get(row)[column];
                        if (codePoint == 0 || codePoint == ' ') {
                            continue;
                        }
                        if (!hasPixels(image, column * cellWidth, row * cellHeight,
                                cellWidth, cellHeight)) {
                            blank.add("%s declares U+%04X at row %d column %d of %s, and that cell"
                                    .formatted(font.id(), codePoint, row, column, bitmap.textureId())
                                    + " is empty");
                        }
                    }
                }
            }
        }
        assertEquals(List.of(), blank, "a declared character with no pixels is not a missing glyph"
                + " on screen - it is a gap the width of the glyph, which reads as a layout bug");
    }

    @Test
    @DisplayName("every drawn cell is claimed by a character")
    void everyDrawnCellIsReachable() {
        final List<String> orphans = new ArrayList<>();
        for (final FontFile font : FONTS) {
            for (final FontFile.Bitmap bitmap : font.bitmaps()) {
                final BufferedImage image = read(bitmap.texture());
                final int cellWidth = image.getWidth() / bitmap.columns();
                final int cellHeight = image.getHeight() / bitmap.rows();
                for (int row = 0; row < bitmap.rows(); row++) {
                    for (int column = 0; column < bitmap.columns(); column++) {
                        if (bitmap.grid().get(row)[column] != 0) {
                            continue;
                        }
                        if (hasPixels(image, column * cellWidth, row * cellHeight,
                                cellWidth, cellHeight)) {
                            orphans.add("%s: row %d column %d of %s is drawn but no character"
                                    .formatted(font.id(), row, column, bitmap.textureId())
                                    + " points at it");
                        }
                    }
                }
            }
        }
        assertEquals(List.of(), orphans, "art nothing can reach is art nobody will ever see - it is"
                + " a chars entry somebody forgot, not a spare cell");
    }

    @Test
    @DisplayName("the bossbar font can write German")
    void theBossbarFontCanWriteGerman() {
        final List<String> missing = new ArrayList<>();
        for (final int codePoint : "äöüÄÖÜß".codePoints().toArray()) {
            if (!BOSSBAR_FONT.covers(codePoint)) {
                missing.add(new String(Character.toChars(codePoint)));
            }
        }
        assertEquals(List.of(), missing,
                "nordtal:bossbar carries its own ascii sheet, so a character the vanilla font has"
                        + " is not a character this one has. It shipped without a single umlaut"
                        + " until 2026-09-04, which is why every German HUD string was written"
                        + " around them; resource-pack/tools/draw_ascii_extras.py draws them");
    }

    @Test
    @DisplayName("every character a boss bar line can contain is in the bossbar font")
    void theBossbarFontCoversTheHudStrings() {
        final Map<String, Set<Integer>> missing = new LinkedHashMap<>();
        for (final String bundle : HUD_BUNDLES) {
            properties(bundle).forEach((key, value) -> {
                if (HUD_KEY_PREFIXES.stream().noneMatch(String.valueOf(key)::startsWith)) {
                    return;
                }
                String.valueOf(value).codePoints().forEach(codePoint -> {
                    if (!BOSSBAR_FONT.covers(codePoint)) {
                        missing.computeIfAbsent(bundle + " " + key, ignored -> new TreeSet<>())
                                .add(codePoint);
                    }
                });
            });
        }
        assertEquals(Map.of(), missing,
                "a boss bar line is rendered in nordtal:bossbar, whose ascii sheet is a subset of"
                        + " the vanilla one - a character it does not carry reaches the player as a"
                        + " missing-glyph box in the middle of the HUD. What a placeholder is"
                        + " replaced with at runtime is not checkable from here.");
    }

    @Test
    @DisplayName("the vanilla boss bar sprites are fully transparent")
    void theVanillaBossBarSpritesAreBlank() {
        for (final String sprite : List.of("white_background", "white_progress")) {
            final Path path = RepositoryRoot.resolve(
                    ASSETS + "/minecraft/textures/gui/sprites/boss_bar/" + sprite + ".png");
            final BufferedImage image = read(path);
            assertTrue(!hasPixels(image, 0, 0, image.getWidth(), image.getHeight()),
                    sprite + ".png has to be fully transparent: the whole HUD technique is a"
                            + " vanilla boss bar made invisible with a composed background drawn"
                            + " in its name. A pixel here puts the vanilla bar back on screen"
                            + " behind ours.");
        }
    }

    @Test
    @DisplayName("every texture under nordtal:textures is reachable from a font")
    void noOrphanedFontTexture() {
        final Set<String> referenced = new LinkedHashSet<>();
        FONTS.forEach(font -> font.bitmaps().forEach(bitmap -> referenced.add(bitmap.textureId())));

        final Path textures = RepositoryRoot.resolve(ASSETS + "/nordtal/textures");
        final List<String> orphans = new ArrayList<>();
        try (Stream<Path> walk = Files.walk(textures)) {
            walk.filter(path -> path.toString().endsWith(".png")).forEach(path -> {
                final String relative = textures.relativize(path).toString();
                // item/ is the balloon's model textures, which hang off nordtal/models/item and
                // not off any font. Everything else under textures/ exists for a font.
                if (relative.startsWith("item/")) {
                    return;
                }
                if (!referenced.contains("nordtal:" + relative)) {
                    orphans.add("nordtal:" + relative);
                }
            });
        } catch (final IOException e) {
            throw new UncheckedIOException("cannot walk " + textures, e);
        }
        orphans.sort(String::compareTo);
        assertEquals(List.of(), orphans, "a texture no font names is either a font entry somebody"
                + " forgot or dead weight in the pack zip; both are worth knowing about");
    }

    // --- helpers ---------------------------------------------------------------------------

    /** Feeds every {@code public static final String} constant of {@link Glyphs} to the consumer. */
    private static void forEachGlyph(final java.util.function.BiConsumer<String, String> consumer) {
        for (final Field field : Glyphs.class.getDeclaredFields()) {
            if (!Modifier.isStatic(field.getModifiers()) || !Modifier.isPublic(field.getModifiers())) {
                continue;
            }
            // The font keys are namespaced ids, not code points; BossBarFontTest checks those.
            if (field.getName().startsWith("FONT_")) {
                continue;
            }
            try {
                final Object value = field.get(null);
                if (value instanceof String text) {
                    consumer.accept(field.getName(), text);
                } else if (value instanceof String[] array) {
                    for (int i = 0; i < array.length; i++) {
                        consumer.accept(field.getName() + "[" + i + "]", array[i]);
                    }
                }
            } catch (final IllegalAccessException e) {
                throw new IllegalStateException("cannot read Glyphs." + field.getName(), e);
            }
        }
    }

    /** The font a constant belongs to, taken from its name - the grouping {@link Glyphs} uses. */
    private static FontFile fontFor(final String constant) {
        if (constant.startsWith("BOSSBAR_")) {
            return BOSSBAR_FONT;
        }
        if (constant.startsWith("BOARD_")) {
            return BOARD_FONT;
        }
        return DEFAULT_FONT;
    }

    private static boolean hasPixels(final BufferedImage image, final int x, final int y,
                                     final int width, final int height) {
        for (int row = y; row < y + height; row++) {
            for (int column = x; column < x + width; column++) {
                if ((image.getRGB(column, row) >>> 24) != 0) {
                    return true;
                }
            }
        }
        return false;
    }

    private static BufferedImage read(final Path path) {
        try {
            final BufferedImage image = ImageIO.read(path.toFile());
            if (image == null) {
                throw new IllegalStateException(path + " is not an image ImageIO can read");
            }
            return image;
        } catch (final IOException e) {
            throw new UncheckedIOException("cannot read " + path, e);
        }
    }

    /** Reads a bundle the way {@code Messages} does - UTF-8, never the platform default. */
    private static Properties properties(final String relative) {
        final Properties properties = new Properties();
        try (Reader reader = new InputStreamReader(
                Files.newInputStream(RepositoryRoot.resolve(relative)), StandardCharsets.UTF_8)) {
            properties.load(reader);
        } catch (final IOException e) {
            throw new UncheckedIOException("cannot read " + relative, e);
        }
        return properties;
    }
}
